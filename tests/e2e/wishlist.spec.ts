import { test, expect } from '@playwright/test'
test('local wishlists persist and item details can be edited and removed', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Christmas wishes' })).toBeVisible()
  await page.getByRole('button', { name: 'On sale' }).click()
  await expect(page.locator('.product-card')).toHaveCount(2)
  await page.getByRole('button', { name: 'Make a new list' }).click()
  await page.getByLabel('List name').fill('Birthday ideas')
  await page.getByLabel('A little introduction').fill('A few good things')
  await page.getByRole('button', { name: 'Create my list' }).click()
  await expect(page.getByRole('heading', { name: 'Birthday ideas' })).toBeVisible()
  await page.getByRole('button', { name: 'Add a wish', exact: true }).click()
  await page.getByLabel('Product name').fill('A lovely book')
  await page.getByLabel('Exact variant').fill('Hardcover')
  await page.getByText('Store and shipping details', {exact:true}).click()
  await page.getByLabel('Store', { exact: true }).fill('Bookshop')
  await page.getByLabel('Price in USD', { exact: true }).fill('25.50')
  await page.getByLabel('Product URL', { exact: true }).fill('https://example.com/book')
  await page.getByRole('button', { name: 'Add to wishlist', exact: true }).click()
  await expect(page.locator('.product-card')).toHaveCount(1)
  await page.reload()
  await page.getByRole('button', { name: /Birthday ideas/ }).click()
  await page.getByRole('button', { name: 'A lovely book', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('$25.50')
  await page.getByRole('button', { name: 'Edit item', exact: true }).click()
  await page.getByLabel('Product name').fill('An even lovelier book')
  await page.getByRole('button', { name: 'Save changes', exact: true }).click()
  await expect(page.getByRole('button', { name: 'An even lovelier book', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'An even lovelier book', exact: true }).click()
  await page.getByRole('button', { name: 'Remove item', exact: true }).click()
  await page.getByRole('button', { name: 'Confirm removal', exact: true }).click()
  await expect(page.locator('.product-card')).toHaveCount(0)
  expect(errors).toEqual([])
})
