import {test,expect} from '@playwright/test'
const png=Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+a3XcAAAAASUVORK5CYII=','base64')
test('custom pictures persist and broken images return to the category artwork',async({page})=>{
 await page.route('https://images.example.com/book.png',route=>route.fulfill({contentType:'image/png',body:png}))
 await page.route('https://images.example.com/broken.png',route=>route.abort())
 await page.goto('/')
 await page.getByRole('button',{name:'Add a wish',exact:true}).click()
 await page.getByLabel('Product name',{exact:true}).fill('Picture book')
 await page.getByRole('combobox',{name:'Category',exact:true}).selectOption('Books')
 await page.getByText('Pictures and MSRP',{exact:true}).click()
 await page.getByLabel('Picture style').selectOption('custom')
 await page.getByLabel('Picture URL').fill('https://images.example.com/book.png')
 await expect(page.getByRole('dialog').getByRole('img',{name:'Picture book',exact:true})).toBeVisible()
 await page.getByRole('button',{name:'Add to wishlist',exact:true}).click()
 const card=page.locator('.product-card').filter({has:page.getByRole('button',{name:'Picture book',exact:true})})
 await expect(card.getByRole('img',{name:'Picture book',exact:true})).toBeVisible()
 await page.reload()
 await expect(card.getByRole('img',{name:'Picture book',exact:true})).toBeVisible()
 await page.getByRole('button',{name:'Picture book',exact:true}).click()
 await expect(page.getByRole('dialog').getByRole('img',{name:'Picture book',exact:true})).toBeVisible()
 await page.getByRole('button',{name:'Edit item',exact:true}).click()
 await page.getByLabel('Picture style').selectOption('none')
 await page.getByRole('button',{name:'Save changes',exact:true}).click()
 await expect(card.locator('img')).toHaveCount(0)
 await expect(card.locator('.product-drawing')).toBeVisible()
 await page.getByRole('button',{name:'Picture book',exact:true}).click()
 await page.getByRole('button',{name:'Edit item',exact:true}).click()
 await page.getByLabel('Picture style').selectOption('custom')
 await page.getByLabel('Picture URL').fill('https://images.example.com/broken.png')
 await expect(page.getByRole('dialog')).toContainText('This picture couldn’t load.')
 await page.getByRole('button',{name:'Save changes',exact:true}).click()
 await expect(card.locator('.product-drawing')).toBeVisible()
 await expect(card.locator('img')).toHaveCount(0)
 await page.setViewportSize({width:390,height:844})
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
})
test('signed-out shared lists display item pictures in dark mode',async({page})=>{
 const token='40000000-0000-4000-8000-000000000001'
 const item={id:'item',name:'A shared picture',variant:'Blue',category:'Other',notes:'',msrp_cents:null,msrp_source_url:null,offers:[],image_url:'https://images.example.com/book.png',image_source_url:'https://shop.example.com/item',image_mode:'auto',checked_at:null,last_attempt_at:null,refresh_status:'never',created_at:new Date().toISOString()}
 await page.emulateMedia({colorScheme:'dark'})
 await page.route('https://images.example.com/book.png',route=>route.fulfill({contentType:'image/png',body:png}))
 await page.route(`**/api/share/${token}`,route=>route.fulfill({json:{list:{name:'Picture wishes',occasion:'everyday',description:''},items:[item]}}))
 await page.route(`**/api/share/${token}/history/item`,route=>route.fulfill({json:[]}))
 await page.goto(`/share/${token}`)
 await expect(page.getByRole('img',{name:'A shared picture · Blue',exact:true})).toBeVisible()
 await expect(page.locator('html')).toHaveAttribute('data-theme','dark')
 await page.getByRole('button',{name:'A shared picture',exact:true}).click()
 await expect(page.getByRole('dialog').getByRole('img',{name:'A shared picture · Blue',exact:true})).toBeVisible()
 await expect(page.getByRole('link',{name:'Picture from product listing'})).toHaveAttribute('href','https://shop.example.com/item')
})
