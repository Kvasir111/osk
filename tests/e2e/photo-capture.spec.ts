import { test, expect } from '@playwright/test'
const png = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+a3XcAAAAASUVORK5CYII=', 'base64')

test('mobile photo quick add saves details to multiple lists without persisting the reference photo', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/capture')
  await page.getByRole('button', { name: 'Add from a photo', exact: true }).click()
  const section = page.getByRole('region', { name: 'A wish, in a snap.' })
  await expect(section).toContainText('isn’t saved with the wish')
  await expect(section.locator('input[capture]')).toHaveAttribute('capture', 'environment')
  await section.getByLabel('Take an item photo').setInputFiles({ name: 'item.png', mimeType: 'image/png', buffer: png })
  await expect(section.getByRole('img', { name: 'Your item photo reference' })).toBeVisible()
  await section.getByLabel('Item name', { exact: true }).fill('A beautiful ceramic mug')
  await section.getByLabel('Variant', { exact: true }).fill('Blue')
  await section.getByRole('combobox', { name: 'Item category', exact: true }).selectOption('Home')
  await section.getByLabel('A note for later').fill('Seen at the local shop')
  await section.getByRole('checkbox', { name: 'Someday, maybe', exact: true }).check()
  await page.screenshot({ path: '/tmp/osk-photo-quick-add-mobile.png', fullPage: true })
  await section.getByRole('button', { name: 'Add to 2 lists', exact: true }).click()
  await expect(section.getByRole('status')).toContainText('Christmas wishes, Someday, maybe')
  await expect(section.getByRole('img')).toHaveCount(0)
  const stored = await page.evaluate(() => JSON.parse(localStorage.getItem('osk-demo-v1')!))
  const added = stored.items.filter((item: any) => item.name === 'A beautiful ceramic mug')
  expect(added.map((item: any) => item.list_id).sort()).toEqual(['demo-christmas', 'demo-everyday'])
  expect(added.every((item: any) => item.variant === 'Blue' && item.notes === 'Seen at the local shop' && item.image_url === null && item.checked_at === null && item.offers.length === 0)).toBe(true)
  expect(JSON.stringify(stored)).not.toContain('blob:')
  await page.emulateMedia({ colorScheme: 'dark' })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await section.getByRole('button', { name: 'Add another item' }).click()
  await expect(section.getByRole('img')).toHaveCount(0)
  await expect(section.getByLabel('Item name', { exact: true })).toHaveCount(0)
  await page.reload()
  await page.getByRole('link', { name: 'Back to wishes' }).click()
  await expect(page.getByRole('button', { name: 'A beautiful ceramic mug', exact: true })).toBeVisible()
})

test('photo capture validates files and removing or cancelling discards the reference', async ({ page }) => {
  await page.goto('/capture')
  await page.getByRole('button', { name: 'Add from a photo', exact: true }).click()
  const section = page.getByRole('region', { name: 'A wish, in a snap.' })
  const input = section.getByLabel('Choose an item photo')
  await input.setInputFiles({ name: 'item.svg', mimeType: 'image/svg+xml', buffer: Buffer.from('<svg/>') })
  await expect(section.getByRole('alert')).toContainText('Choose a JPG')
  await expect(section.getByRole('img')).toHaveCount(0)
  await input.setInputFiles({ name: 'item.png', mimeType: 'image/png', buffer: png })
  await section.getByRole('button', { name: 'Remove photo', exact: true }).click()
  await expect(section.getByRole('img')).toHaveCount(0)
  await input.setInputFiles({ name: 'item.png', mimeType: 'image/png', buffer: png })
  await expect(section.getByRole('img')).toBeVisible()
  await section.getByRole('button', { name: 'Cancel photo quick add' }).click()
  await section.getByRole('button', { name: 'Add from a photo', exact: true }).click()
  await expect(section.getByRole('img')).toHaveCount(0)
})
