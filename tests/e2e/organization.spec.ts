import { test, expect } from '@playwright/test'

async function add(page: import('@playwright/test').Page, name:string, price?:string) {
  await page.getByRole('button',{name:'Add a wish',exact:true}).click()
  await page.getByLabel('Product name',{exact:true}).fill(name)
  if(price) {
    await page.getByLabel('Product URL',{exact:true}).fill(`https://shop.example.com/${name.toLowerCase().replaceAll(' ','-')}`)
    await page.getByLabel('Price in USD',{exact:true}).fill(price)
  }
}
test('simple adds, saved search, quick edits, gift preferences and received/archive restoration', async({page})=>{
  await page.setViewportSize({width:390,height:844})
  await page.goto('/')
  await add(page,'A northern lamp','45.50')
  await expect(page.getByLabel('Picture style')).not.toBeVisible()
  await page.getByLabel('How much would you love it?').selectOption('really_want')
  await page.getByLabel('Gift preferences').fill('Warm white; avoid cool blue')
  await page.getByRole('button',{name:'Add to wishlist',exact:true}).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByLabel('Search your saved wishes').fill('warm white')
  await expect(page.locator('.product-card')).toHaveCount(1)
  await expect(page.locator('.product-card')).toContainText('Really want')
  await page.getByLabel('Max price (USD)').fill('40')
  await expect(page.locator('.product-card')).toHaveCount(0)
  await page.getByLabel('Max price (USD)').fill('50')
  await page.getByLabel('Quick edit A northern lamp',{exact:true}).click()
  await page.getByLabel('Exact variant').fill('Large')
  await page.getByLabel('shop.example.com price in USD').fill('39.99')
  await page.getByLabel('A note for your people').fill('For the reading nook')
  await page.getByRole('button',{name:'Save quick changes',exact:true}).click()
  await expect(page.locator('.product-card')).toContainText('$39.99')
  await page.getByRole('button',{name:'A northern lamp',exact:true}).click()
  await expect(page.getByRole('dialog')).toContainText('Warm white; avoid cool blue')
  await page.getByRole('button',{name:'Mark as received',exact:true}).click()
  await expect(page.locator('.product-card')).toHaveCount(0)
  await page.getByRole('combobox',{name:'Wish status',exact:true}).selectOption('received')
  await page.getByRole('button',{name:'A northern lamp',exact:true}).click()
  await expect(page.getByRole('dialog')).toContainText('Received · price checks paused')
  await page.getByRole('button',{name:'Restore to wishlist',exact:true}).click()
  await page.getByRole('combobox',{name:'Wish status',exact:true}).selectOption('active')
  await page.getByRole('button',{name:'A northern lamp',exact:true}).click()
  await page.getByRole('button',{name:'Archive wish',exact:true}).click()
  await page.getByRole('combobox',{name:'Wish status',exact:true}).selectOption('archived')
  await page.reload()
  await page.getByRole('combobox',{name:'Wish status',exact:true}).selectOption('archived')
  await page.getByLabel('Search your saved wishes').fill('reading nook')
  await expect(page.locator('.product-card')).toHaveCount(1)
  await page.getByRole('button',{name:'A northern lamp',exact:true}).click()
  await page.getByRole('button',{name:'Restore to wishlist',exact:true}).click()
  await page.getByRole('combobox',{name:'Wish status',exact:true}).selectOption('active')
  for(const colorScheme of ['light','dark'] as const){
    await page.emulateMedia({colorScheme})
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  }
  await page.getByLabel('Quick edit A northern lamp',{exact:true}).focus()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
})

test('duplicates can reuse an existing wish, cancel with the draft intact, or copy to another list',async({page})=>{
  await page.goto('/')
  await add(page,'A shared book','20')
  await page.getByRole('button',{name:'Add to wishlist',exact:true}).click()
  const count=await page.locator('.product-card').count()
  await add(page,'A shared book','20')
  await page.getByRole('button',{name:'Add to wishlist',exact:true}).click()
  const duplicate=page.getByRole('dialog',{name:'Already among your wishes?'})
  await expect(duplicate).toBeVisible()
  await duplicate.getByRole('button',{name:'Back to my draft',exact:true}).click()
  await expect(page.getByLabel('Product name',{exact:true})).toHaveValue('A shared book')
  await page.getByRole('button',{name:'Add to wishlist',exact:true}).click()
  await duplicate.getByRole('button',{name:'Keep existing wish',exact:true}).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.locator('.product-card')).toHaveCount(count)
  await page.getByRole('button',{name:/Someday, maybe/}).click()
  await add(page,'A shared book','20')
  await page.getByRole('button',{name:'Add to wishlist',exact:true}).click()
  await duplicate.getByRole('button',{name:'Copy existing wish to this list',exact:true}).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByLabel('Search your saved wishes').fill('shared book')
  await page.getByRole('combobox',{name:'Search in',exact:true}).selectOption('all')
  await expect(page.locator('.product-card')).toHaveCount(2)
})

test('selected wishes can be copied and moved between lists together',async({page})=>{
  await page.goto('/')
  for(const name of ['Birch book','Pine book']) {
    await add(page,name)
    await page.getByRole('button',{name:'Add to wishlist',exact:true}).click()
    await expect(page.getByRole('dialog')).toHaveCount(0)
  }
  await page.getByLabel('Search your saved wishes').fill('book')
  await page.getByRole('button',{name:'Select wishes',exact:true}).click()
  await page.getByLabel('Select Birch book',{exact:true}).check()
  await page.getByLabel('Select Pine book',{exact:true}).check()
  await page.getByRole('button',{name:'Copy to list',exact:true}).click()
  await page.getByRole('combobox',{name:'Destination list',exact:true}).selectOption({label:'Someday, maybe'})
  await page.getByRole('button',{name:'Copy wishes',exact:true}).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('button',{name:/Someday, maybe/}).click()
  await expect(page.locator('.product-card')).toHaveCount(2)
  await page.getByRole('button',{name:'Select wishes',exact:true}).click()
  await page.getByRole('button',{name:'Select shown',exact:true}).click()
  await page.getByRole('button',{name:'Move to list',exact:true}).click()
  await page.getByRole('combobox',{name:'Destination list',exact:true}).selectOption({label:'Christmas wishes'})
  await page.getByRole('button',{name:'Move wishes',exact:true}).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.locator('.product-card')).toHaveCount(0)
  await page.reload()
  await page.getByRole('combobox',{name:'Search in',exact:true}).selectOption('all')
  await page.getByLabel('Search your saved wishes').fill('book')
  await expect(page.locator('.product-card')).toHaveCount(4)
})
